#!/bin/bash
# Puts Laser Lab in /Applications: a launcher that opens index.html in its own Brave window with no browser bars.
# The game folder path is baked in: re-run this script if the folder moves.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
APP="${1:-/Applications}/Laser Lab.app"
[ -d "/Applications/Brave Browser.app" ] || { echo "Brave Browser not found in /Applications"; exit 1; }
rm -rf "$APP"; mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$ROOT/app/icon.icns" "$APP/Contents/Resources/icon.icns"
cat > "$APP/Contents/MacOS/launch" <<SH
#!/bin/bash
# Generated by laser-lab/app/install_app.sh - re-run it if the laser-lab folder moves.
exec open -na "Brave Browser" --args --app="file://$ROOT/index.html" --window-size=1080,960
SH
chmod +x "$APP/Contents/MacOS/launch"
cat > "$APP/Contents/Info.plist" <<PL
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>Laser Lab</string>
  <key>CFBundleDisplayName</key><string>Laser Lab</string>
  <key>CFBundleIdentifier</key><string>eu.vandenbruwaene.laser-lab</string>
  <key>CFBundleExecutable</key><string>launch</string>
  <key>CFBundleIconFile</key><string>icon</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>LSMinimumSystemVersion</key><string>11.0</string>
</dict></plist>
PL
touch "$APP"
/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister -f "$APP" >/dev/null 2>&1 || true
echo "installed: $APP"
